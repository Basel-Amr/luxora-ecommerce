const getProductById = (id) =>
  products.find((product) => product.id === Number(id));
const getFeaturedProducts = () =>
  products.filter((product) => product.isFeatured);
const getBestSellerProducts = () =>
  products.filter((product) => product.isBestSeller);
const getProductsByCategory = (category) =>
  products.filter((product) => product.category === category);
const getProductsByTag = (tag) =>
  products.filter((product) =>
    product.tags.includes(String(tag).toLowerCase()),
  );
const getDiscountPercentage = (product) => {
  if (product.oldPrice === null || product.oldPrice <= product.price) return 0;
  return Math.round(
    ((product.oldPrice - product.price) / product.oldPrice) * 100,
  );
};

window.products = products;
window.getProductById = getProductById;
window.getFeaturedProducts = getFeaturedProducts;
window.getBestSellerProducts = getBestSellerProducts;
window.getProductsByCategory = getProductsByCategory;
window.getProductsByTag = getProductsByTag;
window.getDiscountPercentage = getDiscountPercentage;
